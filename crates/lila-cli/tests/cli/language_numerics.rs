//! `language` CLI integration tests: spec abstract operations, coercion,
//! BigInt, exponentiation, JSON, and the string/URI codecs.
//!
//! Split out of [`crate::language`] because that module OOMed as one libtest
//! process on this container — three SIGKILLs at t+1200 s with `avail` falling
//! monotonically to 1.14 GiB — and the only remaining lever is fewer tests per
//! process. See the header of `language.rs` for the measurements, the two
//! refuted runner knobs, and why the split has to be by module file rather than
//! by libtest filter.
//!
//! 33 tests, all heavy. Its chunk is `run_chunk language_numerics
//! language_numerics::` in `scripts/rung1c-chunks.sh`, and it needs BOTH that
//! line and `mod language_numerics;` in `main.rs`: a module with a chunk but no
//! `mod` line is not compiled, its filter selects nothing, libtest exits 0 on
//! `0 passed`, and the done-file banks a chunk that measured nothing. That is
//! the `iterator_helpers` incident, and
//! `known_failures::rung_1c_chunks_cover_every_cli_area_module` is what catches
//! it now.
//!
//! Two members are here on a judgement call rather than by their names, and are
//! named so nobody reads them as misfiled:
//! `run_wasm_backend_succeeds_for_reflect_set_core_fixture` sits with the
//! `spec_*` abstract-operation fixtures because `Reflect.set` is exactly the
//! `Set` abstract operation, beside `spec_get_v` and `spec_has_property_order`;
//! and `run_wasm_backend_succeeds_for_to_locale_string_boxed_receivers_fixture`
//! is a boxing/coercion test. Neither belongs with bindings and scoping, which
//! is what `language.rs` keeps.
//!
//! Do NOT rename this module to anything ending in `language` — the overlap rule
//! keys on `"{other}::".ends_with("{chunk}::")`, and a stem that is a `::`-suffix
//! of another needs a `--skip` or the two chunks double-run each other's tests.

